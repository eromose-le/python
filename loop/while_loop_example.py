# While loop program

count = 0
while count < 5:
    count = count + 1 # increase count by 1
    print("Ethan =: ", count)


# 1st time: count 0, 0 < 5 = true, increament count by 1 = 1, (prints Ethan =: 1)
# 2nd time: count 1, 1 < 5 = true, increament count by 1 = 2, (prints Ethan =: 2)
# 3rd time: count 2, 2 < 5 = true, increament count by 1 = 3, (prints Ethan =: 3)
# 4th time: count 3, 3 < 5 = true, increament count by 1 = 4, (prints Ethan =: 4)
# 5th time: count 4, 4 < 5 = true, increament count by 1 = 5, (prints Ethan =: 5)
# 6th time: count 5, 5 < 5 = false, break the loop