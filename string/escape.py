# A program to demonstrate escape

# Single quote
single_quote = 'Austine\'s'
print(single_quote)

# Double quote
double_quote = "He said, \"Hi!\""
print(double_quote)

# Backslash
backslash = "C:\\Users\\John"
print(backslash)

# Newline, breaks a line
new_line = "Hello\nWorld"
print(new_line)

# Tabs, add extra whitespace
tab = "A\tB\tC"
print(tab)

# Backspace, deletes the char directly infront of it
back_space = "Hello\b!"
print(back_space)

# Carriage return, takes the cursor to the begining of the line and replace the charater
carriage_return = "123456789\rABC"
print(carriage_return)
# 123456789
# ABC
# output - ABC456789

# Unicode character
print("Ω", "\u03A9")
print("©", "\u00a9")

