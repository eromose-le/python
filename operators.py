first_number = 2
second_number = 10
third_number = 30

# Additions
addition_result = first_number + second_number + third_number
print("Addition result = ", addition_result)

# Subtractions
subtraction_result = third_number - second_number
print("Subtraction result = ", subtraction_result)

# Multiplications
multiplication_result = second_number * first_number
print("Multiplication result = ", multiplication_result)

# Division
division_result = second_number / first_number
print("Division result = ", division_result)

# Interger Division
integer_division_result = second_number // first_number
print("Interger division result = ", integer_division_result)

# Modulus
modulus_result = 11 % first_number
print("modulus_result = ", modulus_result)

# Exponentiations
exponentiation_result = second_number ** first_number
print("Exponentiation result = ", exponentiation_result)